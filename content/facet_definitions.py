def validate() -> list[str]:
    """自检：30 个 facet 齐全，且每个都有必需字段。"""
    problems = []
    want = {"code", "name_zh", "name_en", "domain", "domain_zh", "definition",
            "does_not_measure", "boundaries", "anchors", "critiques", "caveats"}
    if len(FACETS) != 30:
        problems.append(f"facet 数 {len(FACETS)} != 30")
    for f, v in FACETS.items():
        missing = want - set(v)
        if missing:
            problems.append(f"{f}: 缺字段 {sorted(missing)}")
        if set(v.get("anchors", {})) != {"1", "2", "3", "4", "5"}:
            problems.append(f"{f}: anchors 档位不全")
        if len(v.get("does_not_measure", [])) < 3:
            problems.append(f"{f}: does_not_measure 少于 3 条")
        if len(v.get("boundaries", [])) < 3:
            problems.append(f"{f}: boundaries 少于 3 条")
        if not v.get("caveats"):
            problems.append(f"{f}: caveats 为空（V8 要求显式声明）")
    return problems


