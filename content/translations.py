def validate() -> list[str]:
    import json
    import os
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    canon = json.load(open(os.path.join(root, "data/ipip-neo-300.json"), encoding="utf-8"))
    base = json.load(open(os.path.join(root, "data/ipip-neo-120-mandarin.json"), encoding="utf-8"))

    def norm(s):
        return s.lower().replace(" ", "").replace("-", "").replace("_", "")

    problems = []
    if len(TRANSLATIONS) != 183:
        problems.append(f"条目数 {len(TRANSLATIONS)} != 183")
    base_orders = set()
    for f in {i["facet"] for i in canon["items"]}:
        bi = {norm(i["en"]) for i in base["items"] if i["facet"] == f}
        for i in canon["items"]:
            if i["facet"] == f and norm(i["text"]) not in bi:
                base_orders.add(i["order"])
    missing = base_orders - set(TRANSLATIONS)
    extra = set(TRANSLATIONS) - base_orders
    if missing:
        problems.append(f"缺译 {sorted(missing)[:10]}（共 {len(missing)}）")
    if extra:
        problems.append(f"多余条目 {sorted(extra)[:10]}")
    empty = [k for k, v in TRANSLATIONS.items() if not v.strip()]
    if empty:
        problems.append(f"空译文 {empty}")
    return problems


